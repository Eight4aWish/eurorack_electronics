    ic(sh, "PICO2", (75, 110), pico_nets, ref="A101")

    # Teensy 4.1
    tpins = teensy41_pins()
    by_label = {lab: n for n, lab in tpins.items() if lab.isdigit()}
    tnets = {}
    for net, _f, _p, _g, tlabel, _n in PINMAP:
        tnets[by_label[tlabel]] = net
