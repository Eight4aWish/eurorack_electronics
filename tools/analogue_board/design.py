        for n in pins:
            p = j.p(str(n))
            sh.wire(p, (bx, p[1]))
        top, bot = j.p(str(pins[0]))[1], j.p(str(pins[-1]))[1]
        mid = j.p(str(pins[1]))[1]
        sh.wire((bx, top), (bx, bot))
        sh.wire((bx, mid), (bx + 2 * dx, mid))
        sh.power("GND", (bx + 2 * dx, mid), "left" if dx < 0 else "right")
        sh.tie("GND", *[(j, str(n)) for n in pins])

